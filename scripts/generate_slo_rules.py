import json
from pathlib import Path

CONFIG = Path("deploy/prometheus/slo-config.json")
OUTPUT = Path("deploy/prometheus/miniapm-slo-rules.yml")


def selector(config, extra=""):
    fields = {key: config[key] for key in ("dataset_id", "environment", "service", "route", "source_kind")}
    if extra:
        fields["status"] = "error"
    return ",".join(f'{key}="{value}"' for key, value in fields.items())


def main():
    config = json.loads(CONFIG.read_text())
    selected = selector(config)
    errors = selector(config, "status=error")
    allowed = 1 - config["availability_target"]
    fast = config["fast_budget_fraction"] * config["budget_hours"]
    slow = config["slow_budget_fraction"] * config["budget_hours"] / 6
    qps = config["minimum_qps"]
    common_labels = f'policy: "experiment"\n          dataset_id: "{config["dataset_id"]}"\n          service: "order"'
    rules = []
    for window in ("1h", "5m", "6h", "30m"):
        rules.append(f"""      - record: miniapm:order_error_burn_rate:{window}
        expr: sum(rate(miniapm_requests_total{{{errors}}}[{window}])) / sum(rate(miniapm_requests_total{{{selected}}}[{window}])) / {allowed}
        labels:
          dataset_id: "{config['dataset_id']}"
          service: "order"
          window: "{window}\"""")
    for name, long_rate, short_rate, threshold, short_window, strategy in (
        ("MiniapmAvailabilityFastBurn", "1h", "5m", fast, "5m", "fast_burn"),
        ("MiniapmAvailabilitySlowBurn", "6h", "30m", slow, "30m", "slow_burn"),
    ):
        rules.append(f"""      - alert: {name}
        expr: (miniapm:order_error_burn_rate:{long_rate} > {threshold}) and on (dataset_id, service) (miniapm:order_error_burn_rate:{short_rate} > {threshold}) and on (dataset_id, service) (sum by (dataset_id, service) (rate(miniapm_requests_total{{{selected}}}[{short_window}])) > {qps})
        for: 1m
        labels:
          {common_labels}
          strategy: "{strategy}"
        annotations:
          summary: "SLO {strategy} for order POST /orders\"""")
    gauge_selector = selected + f',instance="{config["gauge_instance"]}",version="{config["gauge_version"]}"'
    sigma = config["gauge_sigma"]
    rules.append(f"""      - alert: MiniapmInFlightSigma
        expr: miniapm_requests_in_flight{{{gauge_selector}}} > (avg_over_time(miniapm_requests_in_flight{{{gauge_selector}}}[1h] offset 1h) + {sigma} * stddev_over_time(miniapm_requests_in_flight{{{gauge_selector}}}[1h] offset 1h))
        for: 1m
        labels:
          {common_labels}
          strategy: "gauge_3sigma"
        annotations:
          summary: "In-flight requests exceed historical mean plus {sigma} sigma\"""")
    rules.append(f"""      - alert: MiniapmInFlightFixed
        expr: miniapm_requests_in_flight{{{gauge_selector}}} > {config['gauge_fixed_threshold']}
        for: 1m
        labels:
          {common_labels}
          strategy: "gauge_fixed"
        annotations:
          summary: "In-flight requests exceed fixed threshold\"""")
    latency = config["latency_target_seconds"]
    slow_fraction = config["latency_slow_fraction"]
    rules.append(f"""      - alert: MiniapmLatencySLO
        expr: (1 - sum(rate(miniapm_request_duration_seconds_bucket{{{selected},le="{latency}"}}[5m])) / sum(rate(miniapm_request_duration_seconds_bucket{{{selected},le="+Inf"}}[5m])) > {slow_fraction}) and (sum(rate(miniapm_request_duration_seconds_bucket{{{selected},le="+Inf"}}[5m])) > {qps})
        for: 1m
        labels:
          {common_labels}
          strategy: "latency_slo"
        annotations:
          summary: "More than 1 percent of requests exceed 0.5 seconds\"""")
    rules.append(f"""      - alert: MiniapmLatencyP95Comparison
        expr: (histogram_quantile(0.95, sum by (le) (rate(miniapm_request_duration_seconds_bucket{{{selected}}}[5m]))) > {latency}) and (sum(rate(miniapm_request_duration_seconds_bucket{{{selected},le="+Inf"}}[5m])) > {qps})
        for: 1m
        labels:
          {common_labels}
          strategy: "p95_fixed"
        annotations:
          summary: "P95 exceeds 0.5 seconds for comparison\"""")
    content = "# Generated by scripts/generate_slo_rules.py; edit slo-config.json instead.\ngroups:\n  - name: miniapm-slo-experiments\n    interval: 15s\n    rules:\n" + "\n".join(rules) + "\n"
    OUTPUT.write_text(content)
    print(json.dumps({"output": str(OUTPUT), "rules": len(rules), "fast_threshold": fast, "slow_threshold": slow}))


if __name__ == "__main__":
    main()
